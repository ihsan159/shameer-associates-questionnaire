-- ==============================================================================
-- POST-MIGRATION IDENTITY SEQUENCE SYNCHRONIZATION FUNCTION
-- Dynamically inspects all public identity columns.
-- Handles empty tables (nextval returns 1) and populated tables (nextval returns MAX(id) + 1).
-- ==============================================================================
CREATE OR REPLACE FUNCTION sync_all_identity_sequences()
RETURNS void AS $$
DECLARE
    row_item RECORD;
    max_id BIGINT;
    seq_name TEXT;
BEGIN
    FOR row_item IN
        SELECT table_schema, table_name, column_name
        FROM information_schema.columns
        WHERE is_identity = 'YES'
          AND table_schema = 'public'
        ORDER BY table_name
    LOOP
        -- Retrieve the exact sequence bound to this identity column
        seq_name := pg_get_serial_sequence(
            format('%I.%I', row_item.table_schema, row_item.table_name),
            row_item.column_name
        );

        IF seq_name IS NOT NULL THEN
            -- Calculate the current maximum ID in the table
            EXECUTE format(
                'SELECT MAX(%I) FROM %I.%I',
                row_item.column_name,
                row_item.table_schema,
                row_item.table_name
            ) INTO max_id;

            IF max_id IS NULL THEN
                -- Empty table: setval with is_called = false guarantees nextval() returns 1
                PERFORM setval(seq_name, 1, false);
            ELSE
                -- Populated table: setval with is_called = true guarantees nextval() returns max_id + 1
                PERFORM setval(seq_name, max_id, true);
            END IF;
        END IF;
    END LOOP;
END;
$$ LANGUAGE plpgsql;
